const fs = require('fs')
const path = require('path')
const { normalizeKeys, generateKey, latestVersion } = require('./crypto')

/*
The key file is the module your server code imports. It holds the decryption
key(s) and exports `env()`. The CLI never executes it (it may be TypeScript or
ESM); it reads and edits the key lines as text.
*/

const PACKAGE_NAME = 'preseal'
const DEFAULT_DIRS = ['src', '.']
const DEFAULT_NAMES = ['env-key.js', 'env-key.cjs', 'env-key.mjs', 'env-key.ts']
// `v1: 'base64-of-32-bytes'` in any quote style.
const KEY_LINE_RE = /\b(v[1-9]\d*)\s*:\s*(['"`])([A-Za-z0-9+/]{43}=)\2/g
const POST_URL = 'https://davidwells.io/blog/encrypt-env-vars-before-your-host-sees-them'

/** @typedef {'cjs' | 'esm' | 'ts'} KeyFileFormat */

function readJson(file) {
  try {
    return JSON.parse(fs.readFileSync(file, 'utf8'))
  } catch (err) {
    return null
  }
}

/**
 * Pick the module flavor for a project.
 * @param {string} cwd
 * @returns {KeyFileFormat}
 */
function detectFormat(cwd) {
  if (fs.existsSync(path.join(cwd, 'tsconfig.json'))) return 'ts'
  const pkg = readJson(path.join(cwd, 'package.json'))
  return pkg && pkg.type === 'module' ? 'esm' : 'cjs'
}

/**
 * Where `init` writes the key file when no path is given.
 * @param {string} cwd
 * @param {KeyFileFormat} format
 * @returns {string} absolute path
 */
function defaultKeyFilePath(cwd, format) {
  const dir = fs.existsSync(path.join(cwd, 'src')) ? 'src' : '.'
  const pkg = readJson(path.join(cwd, 'package.json'))
  const isModulePkg = Boolean(pkg && pkg.type === 'module')
  let ext = '.js'
  if (format === 'ts') ext = '.ts'
  else if (format === 'esm' && !isModulePkg) ext = '.mjs'
  else if (format === 'cjs' && isModulePkg) ext = '.cjs'
  return path.join(cwd, dir, `env-key${ext}`)
}

/**
 * Find the key file: an explicit path, then package.json `"preseal": { "keyFile" }`,
 * then `src/env-key.*` and `./env-key.*`.
 * @param {string} cwd
 * @param {string} [explicit]
 * @returns {string | null} absolute path, or null when there is none
 */
function findKeyFile(cwd, explicit) {
  if (explicit) return path.resolve(cwd, explicit)
  const pkg = readJson(path.join(cwd, 'package.json'))
  const configured = pkg && pkg['preseal'] && pkg['preseal'].keyFile
  if (configured) return path.resolve(cwd, configured)
  for (const dir of DEFAULT_DIRS) {
    for (const name of DEFAULT_NAMES) {
      const file = path.join(cwd, dir, name)
      if (fs.existsSync(file)) return file
    }
  }
  return null
}

/**
 * Read the keys out of a key file's source text.
 * @param {string} text
 * @returns {Record<string, string>} version → base64 key (empty when none found)
 */
function parseKeys(text) {
  /** @type {Record<string, string>} */
  const keys = {}
  for (const match of text.matchAll(KEY_LINE_RE)) keys[match[1]] = match[3]
  return keys
}

/**
 * Add a key version to a key file's source text, after the last existing key.
 * @param {string} text
 * @param {string} version
 * @param {string} key
 * @returns {string}
 */
function addKey(text, version, key) {
  const matches = Array.from(text.matchAll(KEY_LINE_RE))
  if (!matches.length) throw new Error('preseal: no key lines found in the key file')
  if (matches.some((match) => match[1] === version)) {
    throw new Error(`preseal: key ${version} is already in the key file`)
  }
  const last = matches[matches.length - 1]
  const lineStart = text.lastIndexOf('\n', last.index) + 1
  let lineEnd = text.indexOf('\n', last.index)
  if (lineEnd === -1) lineEnd = text.length
  const line = text.slice(lineStart, lineEnd)
  const indent = /^\s*/.exec(line)[0]
  const quote = last[2]
  // The last key line needs a trailing comma before another one follows it.
  const fixedLine = /,\s*(\/\/.*)?$/.test(line) ? line : line.replace(/(['"`])(\s*(\/\/.*)?)$/, '$1,$2')
  return `${text.slice(0, lineStart)}${fixedLine}\n${indent}${version}: ${quote}${key}${quote},${text.slice(lineEnd)}`
}

const HEADER = [
  '// Generated by preseal. Server code only: never import this from browser code.',
  '//',
  '// Yes, the key is in source on purpose. The ciphertext lives on your host',
  '// (Netlify, AWS SSM, 1Password), the key lives here. Neither is useful alone.',
  `// ${POST_URL}`
]

function keyLines(keys) {
  return Object.keys(keys).map((version) => `  ${version}: '${keys[version]}',`)
}

/**
 * Render the key module.
 * @param {object} opts
 * @param {Record<string, string>} opts.keys
 * @param {KeyFileFormat} [opts.format]
 * @param {boolean} [opts.standalone] - inline the decrypt code so the app has no dependency on this package
 * @returns {string}
 */
function renderKeyFile({ keys, format = 'cjs', standalone = false }) {
  const ts = format === 'ts'
  const esm = format !== 'cjs'
  const lines = HEADER.slice()

  if (standalone) {
    lines.push(esm ? "import crypto from 'node:crypto'" : "const crypto = require('crypto')")
  } else {
    lines.push(esm ? `import { createEnv } from '${PACKAGE_NAME}'` : `const { createEnv } = require('${PACKAGE_NAME}')`)
  }

  lines.push('')
  lines.push(ts ? "if (typeof (globalThis as any).document !== 'undefined') {" : "if (typeof document !== 'undefined') {")
  lines.push("  throw new Error('env-key was imported in browser code. It must stay on the server.')")
  lines.push('}')
  lines.push('')
  lines.push(ts ? 'const ENV_KEYS: Record<string, string> = {' : 'const ENV_KEYS = {')
  lines.push(...keyLines(keys))
  lines.push('}')
  lines.push('')

  if (standalone) {
    lines.push(
      '// enc:<version>:base64( iv[12] || authTag[16] || ciphertext ), AES-256-GCM.',
      '// Values without the enc: prefix pass through, so a local .env keeps working.',
      ts ? 'function decrypt(value: string | undefined): string | undefined {' : 'function decrypt(value) {',
      "  const match = /^enc:(v\\d+):/.exec(value || '')",
      '  if (!value || !match) return value',
      '  const key = ENV_KEYS[match[1]]',
      '  if (!key) throw new Error(`No key for enc:${match[1]} values`)',
      "  const raw = Buffer.from(value.slice(match[0].length), 'base64')",
      "  const decipher = crypto.createDecipheriv('aes-256-gcm', Buffer.from(key, 'base64'), raw.subarray(0, 12))",
      '  decipher.setAuthTag(raw.subarray(12, 28))',
      "  return Buffer.concat([decipher.update(raw.subarray(28)), decipher.final()]).toString('utf8')",
      '}',
      '',
      '// Decrypted values are kept, so reading a secret again is a lookup.',
      ts ? 'const cache = new Map<string, { raw?: string, value?: string }>()' : 'const cache = new Map()',
      ts ? 'const env = (name: string) => {' : 'const env = (name) => {',
      '  const raw = process.env[name]',
      '  const hit = cache.get(name)',
      '  if (hit && hit.raw === raw) return hit.value',
      '  const value = decrypt(raw)',
      '  cache.set(name, { raw, value })',
      '  return value',
      '}'
    )
  } else {
    lines.push('const env = createEnv(ENV_KEYS)')
  }

  lines.push('')
  lines.push(esm ? 'export { env, ENV_KEYS }' : 'module.exports = { env, ENV_KEYS }')
  return `${lines.join('\n')}\n`
}

/**
 * Load keys from a key file on disk.
 * @param {string} file
 * @returns {Record<string, string>}
 */
function readKeyFile(file) {
  let text
  try {
    text = fs.readFileSync(file, 'utf8')
  } catch (err) {
    throw new Error(`preseal: key file not found: ${file}. Create one with: npx ${PACKAGE_NAME} init`)
  }
  const keys = parseKeys(text)
  if (!Object.keys(keys).length) {
    throw new Error(`preseal: no keys found in ${file}. Expected lines like  v1: '<base64 key>'`)
  }
  return normalizeKeys(keys)
}

/**
 * Create a key file with a fresh `v1` key.
 * @param {object} opts
 * @param {string} opts.cwd
 * @param {string} [opts.file] - path, default `src/env-key.js` (or `./env-key.js` without a `src/` dir)
 * @param {KeyFileFormat} [opts.format] - default: detected from the project
 * @param {boolean} [opts.standalone]
 * @param {boolean} [opts.force] - overwrite an existing file
 * @param {boolean} [opts.dryRun] - work out the file and a key, write nothing
 * @returns {{ file: string, keys: Record<string, string>, format: KeyFileFormat, source: string }}
 */
function createKeyFile({ cwd, file, format, standalone, force, dryRun }) {
  format = format || (file && /\.[cm]?ts$/.test(file) ? 'ts' : detectFormat(cwd))
  const target = file ? path.resolve(cwd, file) : defaultKeyFilePath(cwd, format)
  if (fs.existsSync(target) && !force) {
    throw new Error(
      `preseal: ${path.relative(cwd, target)} already exists. Overwriting it would orphan every value ` +
      'encrypted with its key. Use `preseal rotate` to add a new key, or --force if you mean it.'
    )
  }
  const keys = { v1: generateKey() }
  const source = renderKeyFile({ keys, format, standalone })
  if (dryRun) return { file: target, keys, format, source }
  fs.mkdirSync(path.dirname(target), { recursive: true })
  fs.writeFileSync(target, source)
  rememberKeyFile(cwd, target)
  return { file: target, keys, format, source }
}

/**
 * Record a non-default key file location in package.json so later commands find it.
 * @param {string} cwd
 * @param {string} file - absolute path
 */
function rememberKeyFile(cwd, file) {
  const rel = path.relative(cwd, file).split(path.sep).join('/')
  const isDefault = DEFAULT_DIRS.some((dir) => DEFAULT_NAMES.some((name) => path.posix.join(dir, name) === rel))
  if (isDefault || rel.startsWith('..')) return
  const pkgPath = path.join(cwd, 'package.json')
  let text
  try {
    text = fs.readFileSync(pkgPath, 'utf8')
  } catch (err) {
    return
  }
  let pkg
  try {
    pkg = JSON.parse(text)
  } catch (err) {
    return
  }
  pkg['preseal'] = Object.assign({}, pkg['preseal'], { keyFile: rel })
  const indent = (/^([ \t]+)"/m.exec(text) || [])[1] || 2
  fs.writeFileSync(pkgPath, `${JSON.stringify(pkg, null, indent)}${text.endsWith('\n') ? '\n' : ''}`)
}

/**
 * Add the next key version to a key file. Old keys stay so existing values keep decrypting.
 * @param {string} file
 * @returns {{ version: string, key: string, keys: Record<string, string> }}
 */
function rotateKeyFile(file) {
  const text = fs.readFileSync(file, 'utf8')
  const keys = parseKeys(text)
  if (!Object.keys(keys).length) throw new Error(`preseal: no keys found in ${file}`)
  const version = `v${Number(latestVersion(keys).slice(1)) + 1}`
  const key = generateKey()
  fs.writeFileSync(file, addKey(text, version, key))
  return { version, key, keys: Object.assign({}, keys, { [version]: key }) }
}

module.exports = {
  PACKAGE_NAME,
  detectFormat,
  defaultKeyFilePath,
  findKeyFile,
  parseKeys,
  addKey,
  renderKeyFile,
  readKeyFile,
  createKeyFile,
  rotateKeyFile
}
